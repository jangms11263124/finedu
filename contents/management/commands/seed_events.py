class Command(BaseCommand):
    help = "2026 서울머니쇼 행사 데이터를 삽입합니다 (seoulmoneyshow.com 크롤링 기반)"

    def add_arguments(self, parser):
        parser.add_argument(
            "--no-clear", action="store_true",
            help="기존 이벤트 데이터를 삭제하지 않고 추가만 합니다",
        )

    def handle(self, *args, **options):
        if not options["no_clear"]:
            deleted, _ = Event.objects.all().delete()
            self.stdout.write(f"기존 이벤트 {deleted}건 삭제 완료")

        created = 0
        for title, summary, body, start_date, end_date in EVENTS:
            status = "closed"  # 2026-05-07~09 행사는 이미 종료
            Event.objects.create(
                title=title,
                summary=summary,
                body=body,
                status=status,
                region=REGION,
                online_type=ONLINE,
                host=HOST,
                start_date=start_date,
                end_date=end_date,
                place_name=PLACE,
                address=ADDRESS,
            )
            created += 1

        self.stdout.write(self.style.SUCCESS(
            f"\n완료: 2026 서울머니쇼 이벤트 {created}건 삽입됨"
        ))
